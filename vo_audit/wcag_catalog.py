def resolve_user_impact_profile(crit_num):
    """Perfil de personas usuarias afectadas."""
    if not crit_num:
        return "Tecnologías de apoyo y lectores de pantalla (VoiceOver, TalkBack, NVDA)"
    if crit_num.startswith(("1.1", "1.3", "4.1")):
        return "Personas ciegas / Lector de pantalla (VoiceOver, TalkBack, NVDA, JAWS)"
    if crit_num.startswith("1.4"):
        return "Baja visión, daltonismo y fatiga visual"
    if crit_num.startswith(("2.1", "2.4", "2.5")):
        return "Discapacidad motriz y ceguera / Navegación lineal por VoiceOver, teclado y Control por Botón"
    if crit_num.startswith("1.2"):
        return "Personas sordas o con hipoacusia / Ceguera"
    return "Comprensión cognitiva, lectura, aprendizaje y usuarios de lectores de pantalla"


def resolve_wcag_meta(crit_num):
    """Devuelve metadatos completos del criterio WCAG 2.2."""
    parts = (crit_num or "").split(".")
    p_num = parts[0] if parts else "1"
    g_num = "%s.%s" % (parts[0], parts[1]) if len(parts) >= 2 else p_num
    lvl, name_es, name_en, slug = WCAG_CRITERIA.get(
        crit_num, ("AA", crit_num, crit_num, "")
    )
    return {
        "criterion": crit_num,
        "level": lvl,
        "name_es": name_es,
        "name_en": name_en,
        "principle": WCAG_PRINCIPLES.get(p_num, {}).get("es", p_num),
        "guideline": WCAG_GUIDELINES.get(g_num, {}).get("es", g_num),
        "w3c_url": ("https://www.w3.org/WAI/WCAG22/Understanding/%s.html" % slug) if slug else "https://www.w3.org/TR/WCAG22/",
        "user_impact": resolve_user_impact_profile(crit_num),
    }


